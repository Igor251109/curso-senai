notas_turma = [5.5, 9.0, 2.5, 10.0, 7.2, 4.0]

notas_turma.sort()
print("notas da turma em ordem crecente:", notas_turma)
notas_turma.sort(reverse=True)
print("notas da turma em ordem decrecente:", notas_turma)
print(f"o maior número: {max(notas_turma)}")
print(f"o menor numero: {min(notas_turma)}")